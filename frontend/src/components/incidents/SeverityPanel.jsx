import React from "react";
import { SEVERITY_COLORS } from "../../utils/constants";
import { labelize } from "../../utils/format";
import { SeverityBadge } from "../common/Badge";
import Icon from "../common/Icon";

/**
 * Severity Intelligence Panel.
 * Displays the backend's 0–100 rule-based score, level, factor breakdown,
 * explanation, rules_version, and unvalidated-prototype disclaimer.
 */
export default function SeverityPanel({ severity }) {
  if (!severity) return null;

  const {
    score = 0,
    max_score: maxScore = 100,
    level = "Low",
    explanation,
    factors = [],
    rules_version: rulesVersion,
    disclaimer,
  } = severity;

  const pct = maxScore > 0 ? Math.min(100, Math.max(0, Math.round((score / maxScore) * 100))) : 0;
  const accentColor = SEVERITY_COLORS[level] || "#14B8A6";

  return (
    <section className="surface-card severity-panel">
      <div className="panel-header">
        <div>
          <h2 className="section-title">Severity Intelligence Assessment</h2>
          <p className="section-subtitle">
            Explainable rule-based evaluation generated by the backend scoring engine.
          </p>
        </div>
        <span
          className="rules-pill tabular"
          title="Unvalidated six-factor prototype score: people, immediate help, hazard category, hazard signal, event recency and vulnerable population."
        >
          <Icon name="info" size={14} />
          <span>Rules: {rulesVersion || "demo-rules-v2"}</span>
        </span>
      </div>

      <div className="severity-hero">
        <div className="severity-meter-wrap">
          <div className="severity-score-readout">
            <span className="severity-score-num tabular" style={{ color: accentColor }}>
              {score}
            </span>
            <span className="severity-score-max tabular">/ {maxScore}</span>
          </div>
          <SeverityBadge level={level} />
          <div
            className="severity-bar-track"
            role="progressbar"
            aria-valuenow={score}
            aria-valuemin={0}
            aria-valuemax={maxScore}
            aria-label={`Severity score ${score} out of ${maxScore}`}
          >
            <div
              className="severity-bar-fill"
              style={{ width: `${pct}%`, backgroundColor: accentColor }}
            />
          </div>
          <div className="severity-scale-legend tabular">
            <span>0–24 Low</span>
            <span>25–49 Medium</span>
            <span>50–74 High</span>
            <span>75–100 Critical</span>
          </div>
        </div>

        <div className="severity-factors">
          <div className="factors-heading">Contributing Factors</div>
          {factors.map((factor) => {
            const factorPct =
              factor.max_points > 0
                ? Math.min(100, Math.round((factor.points / factor.max_points) * 100))
                : 0;
            return (
              <div key={factor.factor} className="factor-row">
                <div className="factor-row-top">
                  <span className="factor-name">{labelize(factor.factor)}</span>
                  <span className="factor-points tabular">
                    +{factor.points} / {factor.max_points} pts
                  </span>
                </div>
                <div className="factor-bar-track">
                  <div
                    className="factor-bar-fill"
                    style={{ width: `${factorPct}%`, backgroundColor: accentColor }}
                  />
                </div>
                <div className="factor-reason">{factor.reason}</div>
              </div>
            );
          })}
        </div>
      </div>

      {explanation && (
        <div className="explain-callout">
          <strong>Backend Explanation:</strong> {explanation}
        </div>
      )}

      {disclaimer && (
        <div className="prototype-footnote">
          <Icon name="shield" size={14} />
          <span>{disclaimer}</span>
        </div>
      )}
    </section>
  );
}

